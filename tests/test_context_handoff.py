import sys
import time
import unittest
from pathlib import Path
from types import SimpleNamespace
from unittest.mock import patch

ROOT = Path(__file__).resolve().parents[1]
for path in (ROOT / "backend", ROOT / "backend" / "agent"):
    if str(path) not in sys.path:
        sys.path.insert(0, str(path))

import context_handoff as handoff  # noqa: E402
from web_models import EventType  # noqa: E402


def ev(kind, **data):
    return SimpleNamespace(type=kind, data=data)


EVENTS = [
    ev(EventType.USER_MESSAGE, text="old question before clear"),
    ev(EventType.ASSISTANT_MESSAGE, markdown="old answer"),
    ev(EventType.USER_MESSAGE, text="/clear"),
    ev(EventType.USER_MESSAGE, text="Fix the parser", attachments=[{"filename": "f1.png", "name": "trace.png"}]),
    ev(EventType.THINKING, markdown="private reasoning"),
    ev(EventType.CODEX_COMMAND, command="Run: pytest", status="completed"),
    ev(EventType.FILE_CHANGE, path="/repo/parser.py", action="modified", tool="antigravity"),
    ev(EventType.ASSISTANT_MESSAGE, markdown="Fixed the off-by-one in parser.py."),
    ev(EventType.API_METRICS, provider="acp:antigravity"),
    ev(EventType.USER_MESSAGE, text="/approve always_ask"),
    ev(EventType.USER_MESSAGE, text="Now add a test"),
    ev(EventType.FILE_CHANGE, path="/repo/test_parser.py", action="created", tool="antigravity"),
    ev(EventType.GENERATED_ARTIFACT, path="/repo/report.html", media_type="text/html"),
    ev(EventType.ASSISTANT_MESSAGE, markdown="Added test_parser.py; it passes."),
    ev(EventType.API_METRICS, provider="codex-app-server"),
    ev(EventType.API_METRICS, provider="acp:antigravity"),
]


class CollectTests(unittest.TestCase):
    def test_keeps_messages_replies_and_files_since_last_clear(self):
        transcript = handoff.collect(EVENTS)
        self.assertEqual(transcript.user_messages, ["Fix the parser", "Now add a test"])
        self.assertEqual(transcript.agent_replies, [
            "Fixed the off-by-one in parser.py.", "Added test_parser.py; it passes."])
        self.assertEqual(transcript.files, [
            ("trace.png", "attached by the user"),
            ("/repo/parser.py", "modified by the agent"),
            ("/repo/test_parser.py", "created by the agent"),
            ("/repo/report.html", "generated by the agent"),
        ])

    def test_render_leaves_out_reasoning_and_tool_calls(self):
        text = handoff.render(handoff.collect(EVENTS), "Fixed and tested the parser.", "Antigravity")
        self.assertIn("moved to you from Antigravity", text)
        self.assertIn("1. Fix the parser\n2. Now add a test", text)
        self.assertIn("Summary of the replies so far, written by Antigravity:\nFixed and tested the parser.", text)
        named = handoff.render(handoff.collect(EVENTS), "", "Codex", {"acp:antigravity": "Antigravity",
                                                                      "codex-app-server": "Codex"}.get)
        self.assertIn("in order: Antigravity, Codex.", named)
        neutral = handoff.render(handoff.collect(EVENTS), "Fixed it.", "Antigravity", by_outgoing=False)
        self.assertIn("Summary of the replies so far:\nFixed it.", neutral)
        self.assertNotIn("written by", neutral)
        self.assertIn("- /repo/test_parser.py (created by the agent)", text)
        self.assertNotIn("private reasoning", text)
        self.assertNotIn("pytest", text)
        self.assertNotIn("old question", text)

    def test_long_user_messages_are_trimmed(self):
        transcript = handoff.collect([ev(EventType.USER_MESSAGE, text="x" * 5000)])
        text = handoff.render(transcript, "", "Codex")
        self.assertIn("(truncated; 3000 more characters)", text)

    def test_files_note_and_empty_thread(self):
        self.assertIn("/repo/parser.py", handoff.files_note(handoff.collect(EVENTS)))
        self.assertIsNone(handoff.files_note(handoff.collect([ev(EventType.USER_MESSAGE, text="hi")])))
        self.assertEqual(handoff.build([], None, "Codex"), (None, "none"))


class SummaryTests(unittest.TestCase):
    def setUp(self):
        self.transcript = handoff.collect(EVENTS)

    def test_outgoing_provider_writes_the_summary(self):
        asked = []
        summary, source = handoff.summarize_replies(self.transcript, lambda q: asked.append(q) or "  Did it.  ")
        self.assertEqual((summary, source), ("Did it.", "outgoing"))
        self.assertIn("Leave out your reasoning", asked[0])

    def test_failure_or_timeout_falls_back_to_quoting_replies(self):
        def boom(_question):
            raise RuntimeError("signed out")

        def slow(_question):
            time.sleep(2)
            return "late"

        with patch.object(handoff.utils, "native_enabled", return_value=False):
            for outgoing, timeout in ((boom, 5), (slow, 0.2), (None, 5)):
                summary, source = handoff.summarize_replies(self.transcript, outgoing, timeout=timeout)
                self.assertEqual(source, "fallback")
                self.assertIn("- Added test_parser.py; it passes.", summary)

    def test_native_summary_model_is_the_first_fallback(self):
        reply = {"choices": [{"message": {"content": "Condensed."}}]}
        with (
            patch.object(handoff.utils, "native_enabled", return_value=True),
            patch("harness_agent.call_api", return_value=reply) as call,
        ):
            summary, source = handoff.summarize_replies(self.transcript, None)
        self.assertEqual((summary, source), ("Condensed.", "fallback"))
        self.assertIsNone(call.call_args.kwargs["tools"])


