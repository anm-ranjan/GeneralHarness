"""Context handed to the next provider when a thread switches provider (/model).

The handoff has three parts:
1. the user's messages, verbatim from the transcript (very long ones trimmed),
2. a summary of the agent's final replies, written by the provider being
   switched away from (it has seen the whole session, tool results included),
3. the files and attachments the user and the agent produced, from the
   transcript's file-change, artifact and attachment records.

Tool calls and reasoning are never included. Parts 1 and 3 come from
MyHarness's own records, so they are exact and cost nothing; only part 2 needs
a model. If the outgoing provider cannot answer, the native summary model
condenses the replies instead, and failing that the last replies are quoted.
"""
from __future__ import annotations

import concurrent.futures
from dataclasses import dataclass, field
from typing import Callable

import utils
from web_models import EventType

USER_MESSAGE_LIMIT = 2000
FALLBACK_REPLIES = 3
FALLBACK_REPLY_LIMIT = 1500
SUMMARY_TIMEOUT_SECONDS = 120

SUMMARY_REQUEST = (
    "The user is moving this thread to another assistant. Write a handoff summary of your own "
    "replies in this thread so far: what you did, what you found or decided, and what is still "
    "open or was promised next. Leave out your reasoning, tool calls and file contents; name files "
    "by path. Plain text, at most 300 words. Do not use any tools and do not change anything."
)


@dataclass
class Transcript:
    user_messages: list[str] = field(default_factory=list)
    agent_replies: list[str] = field(default_factory=list)
    files: list[tuple[str, str]] = field(default_factory=list)  # (path or name, how it came about)
    providers: list[str] = field(default_factory=list)  # provider ids that answered, in order

    @property
    def empty(self) -> bool:
        return not (self.user_messages or self.agent_replies)


def collect(events) -> Transcript:
    """User messages, final replies and files since the last /clear."""
    transcript = Transcript()
    seen_files: dict[str, int] = {}

    def add_file(path: str, how: str) -> None:
        path = str(path or "").strip()
        if not path:
            return
        if path in seen_files:
            transcript.files[seen_files[path]] = (path, how)
            return
        seen_files[path] = len(transcript.files)
        transcript.files.append((path, how))

    for event in events:
        data = event.data or {}
        if event.type == EventType.USER_MESSAGE:
            text = str(data.get("text") or "")
            stripped = text.strip()
            if stripped.lower() == "/clear":
                transcript = Transcript()
                seen_files.clear()
                continue
            if stripped.startswith("/") or not stripped:
                continue
            transcript.user_messages.append(stripped)
            for attachment in data.get("attachments") or data.get("images") or []:
                if isinstance(attachment, dict):
                    name = attachment.get("name") or attachment.get("display_name") or attachment.get("filename")
                    add_file(name, "attached by the user")
        elif event.type == EventType.ASSISTANT_MESSAGE:
            markdown = str(data.get("markdown") or "").strip()
            if markdown:
                transcript.agent_replies.append(markdown)
        elif event.type == EventType.FILE_CHANGE:
            add_file(data.get("path"), f"{data.get('action') or 'changed'} by the agent")
        elif event.type == EventType.CODEX_FILE_CHANGE:
            add_file(data.get("path"), "changed by the agent")
        elif event.type == EventType.GENERATED_ARTIFACT:
            add_file(data.get("path"), "generated by the agent")
        elif event.type == EventType.API_METRICS:
            provider = str(data.get("provider") or "")
            if provider and provider not in transcript.providers:
                transcript.providers.append(provider)
    return transcript


def _trim(text: str, limit: int) -> str:
    if len(text) <= limit:
        return text
    return text[:limit].rstrip() + f"\n(truncated; {len(text) - limit} more characters)"


def fallback_summary(transcript: Transcript) -> str:
    """The native summary model condenses the replies; failing that, quote the last ones."""
    replies = transcript.agent_replies
    if not replies:
        return ""
    if utils.native_enabled():
        try:
            import harness_agent as agent

            body = "\n\n---\n\n".join(replies)
            answer = agent.call_api(
                [
                    {"role": "system", "content": "You write short handoff summaries of an assistant's work."},
                    {"role": "user", "content": f"{SUMMARY_REQUEST}\n\nThe replies, oldest first:\n\n{body}"},
                ],
                tools=None,
                model=utils.SUMMARY_MODEL,
                max_tokens=1024,
                timeout=SUMMARY_TIMEOUT_SECONDS,
                capture_purpose="provider_handoff",
            )
            text = _message_text(answer)
            if text:
                return text
        except Exception:
            pass
    recent = replies[-FALLBACK_REPLIES:]
    quoted = "\n\n".join(f"- {_trim(reply, FALLBACK_REPLY_LIMIT)}" for reply in recent)
    lead = "The agent's last replies" if len(replies) > len(recent) else "The agent's replies"
    return f"{lead} (no summary could be written):\n{quoted}"


def _message_text(answer) -> str:
    if isinstance(answer, str):
        return answer.strip()
    if isinstance(answer, dict):
        message = answer.get("message") if isinstance(answer.get("message"), dict) else answer
        choices = answer.get("choices")
        if isinstance(choices, list) and choices:
            message = choices[0].get("message") or {}
        content = message.get("content")
        if isinstance(content, str):
            return content.strip()
    return ""


def summarize_replies(transcript: Transcript, outgoing: Callable[[str], str] | None,
                      timeout: float = SUMMARY_TIMEOUT_SECONDS) -> tuple[str, str]:
    """(summary, source): the outgoing provider's own summary, else the fallback."""
    if not transcript.agent_replies:
        return "", "none"
    if outgoing is not None:
        pool = concurrent.futures.ThreadPoolExecutor(max_workers=1)
        try:
            text = (pool.submit(outgoing, SUMMARY_REQUEST).result(timeout=timeout) or "").strip()
            if text:
                return text, "outgoing"
        except Exception:
            pass
        finally:
            pool.shutdown(wait=False)
    return fallback_summary(transcript), "fallback"


def render(transcript: Transcript, summary: str, from_label: str,
           label: Callable[[str], str] | None = None) -> str:
    """The handoff text the next provider receives before the user's next message."""
    parts = [
        f"This thread was moved to you from {from_label}. What happened so far:",
    ]
    names = list(dict.fromkeys((label or str)(p) for p in transcript.providers))
    if len(names) > 1:
        parts.append(
            f"Assistants that worked in this thread, in order: {', '.join(names)}. "
            f"{from_label} saw the earlier assistants' replies as its own history, so its summary "
            "may describe their work as its own."
        )
    if transcript.user_messages:
        lines = "\n".join(
            f"{i}. {_trim(text, USER_MESSAGE_LIMIT)}" for i, text in enumerate(transcript.user_messages, 1)
        )
        parts.append(f"The user's messages, oldest first:\n{lines}")
    if summary:
        parts.append(f"Summary of the replies so far, written by {from_label}:\n{summary}")
    if transcript.files:
        lines = "\n".join(f"- {path} ({how})" for path, how in transcript.files)
        parts.append(f"Files and attachments in this thread:\n{lines}")
    return "\n\n".join(parts)


def files_note(transcript: Transcript) -> str | None:
    """Only the file list, for a target that already rebuilds the messages itself."""
    if not transcript.files:
        return None
    lines = "\n".join(f"- {path} ({how})" for path, how in transcript.files)
    return f"Files and attachments in this thread:\n{lines}"


def build(events, outgoing: Callable[[str], str] | None, from_label: str,
          label: Callable[[str], str] | None = None) -> tuple[str | None, str]:
    """(handoff text or None when there is nothing to hand over, summary source)."""
    transcript = collect(events)
    if transcript.empty:
        return None, "none"
    summary, source = summarize_replies(transcript, outgoing)
    return render(transcript, summary, from_label, label), source
